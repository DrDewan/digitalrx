const DICTIONARIES: Record<Language, Partial<Dict>> = { en, bn };

export function translate(lang: Language, key: DictKey): string {
  return DICTIONARIES[lang]?.[key] ?? en[key] ?? String(key);
}

/** Curried translator, e.g. `const t = translator(lang); t("save")`. */
export function translator(lang: Language) {
  return (key: DictKey) => translate(lang, key);
}

